import { stub } from "jest-auto-stub";

import { CrashBetHandler } from "../../../../src/game-crash/bet";
import { ProvablyFairStore } from "../../../../src/game-crash/provably-fair";

import { AutoCashOutStore } from "../../../../src/game-crash/auto-cash-out";
import { BetInputStore } from "../../../../src/game-crash/bet-input/bet-input-store";
import { BetStore } from "../../../../src/game/bets";
import { BetHandlerBase } from "../../../../src/game/bets/bet-handler-base";
import { GameSetting } from "../../../../src/game/game-configs/game-setting";
import { NoticeStore } from "../../../../src/game/notices";
import { RoundStore, RoundTimeStore } from "../../../../src/game/rounds";
import { MainPlayerStore } from "../../../../src/players";
import { gameSettings } from "../../container.test";
import { ConnectionHandlers, ConnectionStore } from "./../../../../src/game/connection";
import { OrientationStore } from "./../../../../src/game/orientation";
jest.mock("../../../../src/shared/utils/localization-manager", () => ({
    Translator: { translate: jest.fn(), gameTranslate: jest.fn(), commonTranslate: jest.fn().mockImplementation((key, option) => key) },
}));

describe("CrashBetHandler", () => {
    let handler: CrashBetHandler;

    let connectionStore: ConnectionStore;
    let betStore: BetStore;
    let mainPlayerStore: MainPlayerStore;
    let orientationStore: OrientationStore;
    let roundTimeStore: RoundTimeStore;
    let noticeStore: NoticeStore;
    let retryHandler: ConnectionHandlers.RetryGameHandler;
    let showWarningProcessingBet;
    let gameSetting: GameSetting;
    let autoCashOutStore: AutoCashOutStore;
    let betInputStore: BetInputStore;
    let roundStore: RoundStore;
    let pfStore: ProvablyFairStore;
    const clientSeed = "9999";

    beforeAll(() => {
        noticeStore = new NoticeStore();
        mainPlayerStore = new MainPlayerStore(noticeStore);
        connectionStore = stub<ConnectionStore>();
        betStore = stub<BetStore>();
        orientationStore = new OrientationStore();
        retryHandler = stub<ConnectionHandlers.RetryGameHandler>();
        autoCashOutStore = stub<AutoCashOutStore>();
        roundStore = stub<RoundStore>();
        betInputStore = stub<BetInputStore>();
        pfStore = stub<ProvablyFairStore>({
            clientSeed,
        });

        roundTimeStore = new RoundTimeStore(gameSettings);
        gameSetting = new GameSetting();
    });

    beforeEach(() => {
        handler = new CrashBetHandler(
            connectionStore,
            betStore,
            mainPlayerStore,
            orientationStore,
            roundTimeStore,
            noticeStore,
            retryHandler,
            gameSetting,
            roundStore,
            autoCashOutStore,
            betInputStore,
            pfStore
        );

        showWarningProcessingBet = jest.spyOn(handler, "showWarningProcessingBet");

        connectionStore.send = jest.fn();
        noticeStore.addWarning = jest.fn();
        noticeStore.addProcessWarning = jest.fn();
        mainPlayerStore.name = "player";
        betStore.isProcessingBet = false;
    });

    afterEach(() => {
        jest.clearAllMocks();
    });

    describe("handle", () => {
        it("should call handleBetData ", () => {
            // Arrange
            const betData = {};
            handler.handleBetData = jest.fn();
            handler.createBetData = jest.fn(() => betData);
            // Act
            handler.handle();

            // Assert
            expect(handler.createBetData).toBeCalled();
            expect(handler.handleBetData).toBeCalledWith(betData);
        });
    });

    describe("getBetAmount", () => {
        it("should return value by betInputStore.betAmount ", () => {
            // Arrange
            let result = 0;
            betInputStore.betAmount = 10;

            // Act
            result = handler.getBetAmount();

            // Assert
            expect(result).toEqual(betInputStore.betAmount);
        });
    });

    // Generated by CodiumAI

    describe("createBetData", () => {
        let createBetDataSpy;
        let undefinedAutoCashOutData;
        let autoCashOutData;
        beforeEach(() => {
            autoCashOutStore.enable = false;
            autoCashOutStore.multiplier = 1.5;
            roundStore._clientRoundId = 1;
            createBetDataSpy = jest.spyOn(BetHandlerBase.prototype, "createBetData").mockReturnValue({});

            undefinedAutoCashOutData = {
                autoCashOut: undefined,
                roundId: roundStore.clientRoundId,
                clientSendTime: expect.any(Date),
                clientSeed,
            };
            autoCashOutData = {
                autoCashOut: autoCashOutStore.multiplier,
                roundId: roundStore.clientRoundId,
                clientSendTime: expect.any(Date),
                clientSeed,
            };
        });

        afterEach(() => {
            // Clean up
            createBetDataSpy.mockRestore();
        });
        it("should call super.createBetData with the given data and merge with autoCashOut, roundId, and clientSendTime", () => {
            // Arrange
            const data = {};

            // Act
            const result = handler.createBetData(data);

            // Assert
            expect(createBetDataSpy).toHaveBeenCalledWith(data);
            expect(result).toEqual(expect.objectContaining(undefinedAutoCashOutData));
        });

        it("should set autoCashOut to undefined when autoCashOutStore.enable is false", () => {
            // Arrange
            const data = {};

            // Act
            const result = handler.createBetData(data);

            // Assert
            expect(result).toEqual(expect.objectContaining(undefinedAutoCashOutData));
        });

        it("should set autoCashOut to autoCashOutStore.multiplier when autoCashOutStore.enable is true", () => {
            // Arrange
            const data = {};
            autoCashOutStore.enable = true;

            // Act
            const result = handler.createBetData(data);

            // Assert
            expect(result).toEqual(expect.objectContaining(autoCashOutData));
        });
    });

    describe("autoPlaceBet", () => {
        it("should call handle ", () => {
            // Arrange
            handler.handle = jest.fn();

            // Act
            handler.autoPlaceBet();

            // Assert
            expect(handler.handle).toBeCalled();
        });
    });
});
